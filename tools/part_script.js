function firstOpen(list, lv, exclude){ return list.find(p=>p.level===lv && !S.solved[p.id] && p.id!==exclude) || null; }
// Next problem in a skill: the learner's level first, then the nearest level that still has unsolved work.
function recommendIn(lang, skill, exclude){
  const list = pool(lang,skill), lv = levelOf(lang,skill);
  for (const l of [lv, lv+1, lv+2, lv-1, lv-2]) { if(l<1||l>3) continue; const p=firstOpen(list,l,exclude); if(p) return p; }
  return null;
}
function recommend(lang, preferSkill, exclude){
  const order = SKILLS[lang].map(s=>s[0]);
  const start = preferSkill && !S.done[key(lang,preferSkill)] ? [preferSkill] : [];
  for (const sk of start.concat(order.filter(s=>!S.done[key(lang,s)])).concat(order)) {
    const p = recommendIn(lang, sk, exclude); if (p) return {p};
  }
  const sk = preferSkill || order[0];
  return {gen:{lang, skill:sk, level:levelOf(lang,sk)}};
}
// After a mistake: an unsolved problem in the same skill one or two levels down, else the same level, else ask Claude for an easier one.
function easierThan(p){
  const list = pool(p.lang,p.skill);
  for (const l of [p.level-1, p.level-2]) { if(l<1) continue; const q=firstOpen(list,l,p.id); if(q) return {p:q}; }
  if (p.level===1) { const q=firstOpen(list,1,p.id); if(q) return {p:q}; }
  return {gen:{lang:p.lang, skill:p.skill, level:Math.max(1,p.level-1), easierId:p.id}};
}
function onPass(p){
  const k=key(p.lang,p.skill), clean=!S.fails[p.id] && !S.used[p.id];
  if (S.solved[p.id]) return "";
  S.solved[p.id] = S.used[p.id]==="solution" ? "shown" : (clean ? "clean" : "retry");
  let msg="";
  if (S.used[p.id]==="solution") msg="Solved with the solution shown, so your level stays where it is.";
  else if (clean){
    if (p.level===3){ S.done[k]=true; S.level[k]=3; msg=`First try on a Challenge problem. ${skillName(p.lang,p.skill)} is marked as mastered.`; }
    else if (levelOf(p.lang,p.skill) <= p.level){ S.level[k]=p.level+1; msg=`First try, so you move up to Level ${p.level+1}: ${LEVEL_NAME[p.level+1]}.`; }
  } else {
    if (levelOf(p.lang,p.skill) < p.level){ S.level[k]=p.level; msg=`You got there. You're back at Level ${p.level}.`; }
    if (p.level===3) S.done[k]=true;
  }
  save(); return msg;
}
function onMiss(p, kind){ // kind: 'fail' | 'solution'
  const k=key(p.lang,p.skill), first=!S.fails[p.id] && !S.used[p.id];
  if (kind==="fail") S.fails[p.id]=(S.fails[p.id]||0)+1; else S.used[p.id]="solution";
  let msg="";
  if (first && !S.solved[p.id] && p.level>1 && levelOf(p.lang,p.skill)>=p.level){ S.level[k]=p.level-1; msg=`Your ${skillName(p.lang,p.skill)} level drops to ${p.level-1} for now. Solve this one or the easier question to climb back.`; }
  save(); return msg;
}

