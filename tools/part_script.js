function md(s){ // small renderer for Claude-written task text
  const parts=String(s||"").split(/```[a-zA-Z]*\n?/);
  return parts.map((chunk,i)=> i%2 ? `<pre><code>${esc(chunk.replace(/\n$/,""))}</code></pre>` :
    chunk.split(/\n{2,}/).map(par=>{
      const lines=par.split("\n"); const inl=t=>esc(t).replace(/`([^`]+)`/g,"<code>$1</code>").replace(/\*\*([^*]+)\*\*/g,"<b>$1</b>");
      if(lines.every(l=>/^\s*[-*]\s+/.test(l)||!l.trim())) return "<ul>"+lines.filter(l=>l.trim()).map(l=>`<li>${inl(l.replace(/^\s*[-*]\s+/,""))}</li>`).join("")+"</ul>";
      return par.trim()?`<p>${inl(par).replace(/\n/g,"<br>")}</p>`:"";
    }).join("")).join("");
}
